import { ReactNode, useState } from "react";
import { NavLink } from "react-router-dom";
import { useAuth } from "../contexts/AuthContext";
import GlobalQuickAdd from "./GlobalQuickAdd";

interface LayoutProps {
  children: ReactNode;
}

const navItems = [
  { to: "/", icon: GridIcon, label: "Dashboard", end: true },
  { to: "/daily", icon: DayIcon, label: "Daily View" },
  { to: "/weekly", icon: ListIcon, label: "Weekly View" },
  { to: "/calendar", icon: CalendarIcon, label: "Calendar" },
  { to: "/assignments", icon: BookIcon, label: "Assignments" },
  { to: "/students", icon: UsersIcon, label: "Students" },
  { to: "/classes", icon: AcademicIcon, label: "Classes" },
  { to: "/payments", icon: CurrencyIcon, label: "Payments" },
  { to: "/search", icon: SearchIcon, label: "Search" },
];

export default function Layout({ children }: LayoutProps) {
  const { user, logout } = useAuth();
  const [sidebarOpen, setSidebarOpen] = useState(false);

  async function handleLogout() {
    await logout();
    window.location.replace(`${import.meta.env.BASE_URL}login`);
  }

  return (
    <div className="flex h-screen bg-navy overflow-hidden">
      {sidebarOpen && (
        <div className="fixed inset-0 bg-black/50 z-20 lg:hidden" onClick={() => setSidebarOpen(false)} />
      )}

      <aside className={`fixed lg:static inset-y-0 left-0 z-30 w-64 flex flex-col bg-navy-dark border-r border-slate-700/50 transform transition-transform duration-200 ${sidebarOpen ? "translate-x-0" : "-translate-x-full"} lg:translate-x-0`}>
        <div className="flex items-center gap-3 p-6 border-b border-slate-700/50">
          <div className="w-9 h-9 rounded-lg bg-gold/20 flex items-center justify-center">
            <svg className="w-5 h-5 text-gold" fill="none" stroke="currentColor" viewBox="0 0 24 24">
              <path strokeLinecap="round" strokeLinejoin="round" strokeWidth={2} d="M12 6.253v13m0-13C10.832 5.477 9.246 5 7.5 5S4.168 5.477 3 6.253v13C4.168 18.477 5.754 18 7.5 18s3.332.477 4.5 1.253m0-13C13.168 5.477 14.754 5 16.5 5c1.747 0 3.332.477 4.5 1.253v13C19.832 18.477 18.247 18 16.5 18c-1.746 0-3.332.477-4.5 1.253" />
            </svg>
          </div>
          <div>
            <h1 className="font-display font-bold text-ivory text-sm leading-tight">Academic</h1>
            <p className="text-gold text-xs font-medium">Scheduler</p>
          </div>
        </div>

        <nav className="flex-1 px-3 py-4 space-y-0.5 overflow-y-auto">
          {navItems.map(({ to, icon: Icon, label, end }) => (
            <NavLink
              key={to}
              to={to}
              end={end}
              onClick={() => setSidebarOpen(false)}
              className={({ isActive }) =>
                `flex items-center gap-3 px-3 py-2.5 rounded-lg text-sm font-medium transition-all ${
                  isActive
                    ? "bg-gold/15 text-gold border border-gold/20"
                    : "text-slate-400 hover:text-ivory hover:bg-slate-700/40"
                }`
              }
            >
              <Icon className="w-4 h-4 flex-shrink-0" />
              {label}
            </NavLink>
          ))}
        </nav>

        <div className="p-4 border-t border-slate-700/50">
          <div className="flex items-center gap-3 px-3 py-2 rounded-lg bg-slate-700/30 mb-2">
            <div className="w-8 h-8 rounded-full bg-gold/20 flex items-center justify-center text-gold text-xs font-bold">
              {user?.name?.charAt(0).toUpperCase()}
            </div>
            <div className="flex-1 min-w-0">
              <p className="text-ivory text-sm font-medium truncate">{user?.name}</p>
              <p className="text-slate-400 text-xs truncate">{user?.email}</p>
            </div>
          </div>
          <button onClick={handleLogout} className="w-full flex items-center gap-2 px-3 py-2 text-slate-400 hover:text-red-400 text-sm rounded-lg hover:bg-red-500/10 transition-colors">
            <LogoutIcon className="w-4 h-4" />
            Sign Out
          </button>
        </div>
      </aside>

      <div className="flex-1 flex flex-col min-w-0 overflow-hidden">
        <header className="flex items-center justify-between px-6 py-4 border-b border-slate-700/50 bg-navy-dark lg:hidden">
          <button onClick={() => setSidebarOpen(true)} className="text-slate-400 hover:text-ivory">
            <MenuIcon className="w-6 h-6" />
          </button>
          <span className="font-display font-bold text-ivory">Academic Scheduler</span>
          <div className="w-6" />
        </header>
        <main className="flex-1 overflow-y-auto p-6">{children}</main>
      </div>
      <GlobalQuickAdd />
    </div>
  );
}

